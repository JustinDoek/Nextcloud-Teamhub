/**
 * `{ id, label }` options for NcSelect, named in `locale` and sorted by that
 * name. Falls back to the bare code where the browser has no name for it.
 *
 * @param {string} locale BCP 47 tag, e.g. from getCanonicalLocale()
 * @return {{ id: string, label: string }[]}
 */
export function countryOptions(locale) {
	let names = null
	try {
		names = new Intl.DisplayNames([locale, 'en'], { type: 'region' })
	} catch (e) {
		names = null
	}
	const collator = new Intl.Collator(locale || undefined)
	return COUNTRY_CODES
		.map(code => {
			let label = code
			try {
				label = names?.of(code) || code
			} catch (e) {
				label = code
			}
			return { id: code, label }
		})
		.sort((a, b) => collator.compare(a.label, b.label))
}
